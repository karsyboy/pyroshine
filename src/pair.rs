//! Terminal pairing through the same local, same-user interface as the GUI.

use std::io::{BufRead, IsTerminal, Write};
use std::time::Duration;

use futures_util::StreamExt;
use moonshine_management::dto::{PairingOutcome, PairingResolution, PairingSnapshot, PendingPairing, ServerInfo};
use moonshine_management::{API_VERSION, BUS_NAME, ManagementError, ManagementProxy};

const REQUEST_WAIT: Duration = Duration::from_secs(300);
const POLL_INTERVAL: Duration = Duration::from_millis(500);

pub async fn run(name: &str) -> Result<(), String> {
	let connection = zbus::connection::Builder::session()
		.map_err(bus_error)?
		.method_timeout(Duration::from_secs(5))
		.build()
		.await
		.map_err(bus_error)?;
	let proxy = connect(&connection).await?;
	if !std::io::stdin().is_terminal() {
		return Err("Use an interactive terminal on the host, or SSH with a terminal (ssh -t user@host).".into());
	}
	pair(
		&proxy,
		name,
		&mut std::io::stdin().lock(),
		&mut std::io::stdout().lock(),
		REQUEST_WAIT,
	)
	.await
}

fn bus_error(error: zbus::Error) -> String {
	format!("Cannot reach your session bus: {error}. Run as the streaming user; headless use requires lingering.")
}

fn service_error(error: zbus::Error) -> String {
	let error = ManagementError::from(error);
	format!(
		"{}. Check that Pyroshine is running for this user. After a server restart, run pair again.",
		error.message()
	)
}

async fn connect(connection: &zbus::Connection) -> Result<ManagementProxy<'_>, String> {
	let bus = zbus::fdo::DBusProxy::new(connection).await.map_err(service_error)?;
	let name = zbus::names::BusName::try_from(BUS_NAME).expect("valid management bus name");
	let owner = bus.get_name_owner(name).await.map_err(|error| {
		format!(
			"Cannot reach Pyroshine: {error}. Start the server and run this command as its streaming user, without sudo."
		)
	})?;
	// Bind this invocation to one daemon. A restart must not switch the
	// operator's in-progress approval to another owner's request.
	ManagementProxy::builder(connection)
		.destination(owner)
		.map_err(service_error)?
		.build()
		.await
		.map_err(service_error)
}

fn decode<T: serde::de::DeserializeOwned>(json: &str) -> Result<T, String> {
	serde_json::from_str(json)
		.map_err(|_| "Incompatible management response. Update the server and command together.".into())
}

async fn pending(proxy: &ManagementProxy<'_>) -> Result<Vec<PendingPairing>, String> {
	let snapshot: PairingSnapshot = decode(&proxy.get_pairing().await.map_err(service_error)?)?;
	if !snapshot.enabled {
		return Err("New pairings are disabled. Enable pairing in settings and restart the server.".into());
	}
	Ok(snapshot
		.requests
		.into_iter()
		.filter(|request| !request.approved)
		.collect())
}

fn prompt(input: &mut impl BufRead, output: &mut impl Write, message: &str) -> Result<String, String> {
	write!(output, "{message}")
		.and_then(|()| output.flush())
		.map_err(|error| error.to_string())?;
	let mut line = String::new();
	if input.read_line(&mut line).map_err(|error| error.to_string())? == 0 {
		return Err("Pairing cancelled: no input.".into());
	}
	Ok(line.trim().to_string())
}

// Requester addresses and fingerprints are generated by the daemon, but
// terminal output still must not execute control characters from a response.
fn display(value: &str) -> String {
	value.chars().filter(|character| !character.is_control()).collect()
}

async fn pair(
	proxy: &ManagementProxy<'_>,
	name: &str,
	input: &mut impl BufRead,
	output: &mut impl Write,
	wait: Duration,
) -> Result<(), String> {
	let server: ServerInfo = decode(&proxy.get_server().await.map_err(service_error)?)?;
	if server.api_version != API_VERSION {
		return Err("Incompatible management API. Update the server and command together.".into());
	}
	// Subscribe before reading requests and before approval: a fast client can
	// finish pairing before ApprovePairing returns. Tokens, not client IDs or
	// pre-existing trusted certificates, identify completion of this attempt.
	let mut resolved = proxy.receive_pairing_resolved().await.map_err(service_error)?;
	writeln!(
		output,
		"Start pairing in Moonlight or Pyrolight. Waiting for a request (Ctrl+C to cancel)..."
	)
	.map_err(|error| error.to_string())?;
	let requests = tokio::time::timeout(wait, async {
		loop {
			let requests = pending(proxy).await?;
			if !requests.is_empty() {
				return Ok::<_, String>(requests);
			}
			tokio::time::sleep(POLL_INTERVAL).await;
		}
	})
	.await
	.map_err(|_| {
		"No pairing request received. Check the client's host address and firewall, then try again.".to_string()
	})??;
	for (index, request) in requests.iter().enumerate() {
		writeln!(output, "{}. Requested by: {}", index + 1, display(&request.requester))
			.and_then(|()| {
				writeln!(
					output,
					"   Certificate SHA-256: {}",
					display(request.fingerprint.as_deref().unwrap_or("unknown"))
				)
			})
			.map_err(|error| error.to_string())?;
	}
	let index = if requests.len() == 1 {
		0
	} else {
		loop {
			let selection = prompt(input, output, "Request number (or q to cancel): ")?;
			if selection.eq_ignore_ascii_case("q") {
				return Err("Pairing cancelled.".into());
			}
			if let Ok(number) = selection.parse::<usize>()
				&& (1..=requests.len()).contains(&number)
			{
				break number - 1;
			}
			writeln!(output, "Choose a number from 1 to {}.", requests.len()).map_err(|error| error.to_string())?;
		}
	};
	let request = &requests[index];
	let confirmation = prompt(input, output, "Is this the device you just started pairing? Type yes: ")?;
	if !confirmation.eq_ignore_ascii_case("yes") {
		return Err("Pairing cancelled; no PIN submitted.".into());
	}
	let pin = prompt(input, output, "PIN shown by the client: ")?;
	if pin.len() != 4 || !pin.bytes().all(|byte| byte.is_ascii_digit()) {
		return Err("Enter the four-digit PIN shown by the client, then run pair again.".into());
	}
	proxy
		.approve_pairing(&request.client_id, &request.request, &pin, name)
		.await
		.map_err(|error| ManagementError::from(error).message())?;
	writeln!(output, "PIN submitted. Waiting for the client to finish pairing...")
		.map_err(|error| error.to_string())?;
	// The server's transaction expires one minute after its approval deadline.
	// This is only a client wait limit; it never changes the server's deadline.
	let completion_wait = Duration::from_millis(request.approval_expires_in_ms.min(300_000)) + Duration::from_secs(61);
	let outcome = tokio::time::timeout(completion_wait, async {
		loop {
			tokio::select! {
				signal = resolved.next() => {
					let signal = signal.ok_or_else(|| "The server disconnected before pairing was confirmed.".to_string())?;
					let args = signal.args().map_err(service_error)?;
					let resolution: PairingResolution = decode(args.resolution())?;
					if resolution.client_id == request.client_id && resolution.request == request.request {
						return pairing_outcome(resolution.outcome);
					}
				},
				// Detect a lost daemon promptly, even if no resolution arrives.
				() = tokio::time::sleep(Duration::from_secs(1)) => {
					proxy.get_pairing().await.map_err(service_error)?;
				},
			}
		}
	})
	.await
	.map_err(|_| "Pairing was not confirmed. Check the client and server log before trying again.".to_string())?;
	outcome?;
	writeln!(
		output,
		"Device paired. Select Steam or another application in the client to start streaming."
	)
	.map_err(|error| error.to_string())
}

fn pairing_outcome(outcome: PairingOutcome) -> Result<(), String> {
	match outcome {
		PairingOutcome::Paired => Ok(()),
		PairingOutcome::Failed => {
			Err("The client could not complete pairing. Check its PIN and start pairing again.".into())
		},
		PairingOutcome::Replaced => {
			Err("The client sent a new request. Start pairing again and check the new request/PIN.".into())
		},
		PairingOutcome::Expired => Err("The request expired. Start pairing again in the client.".into()),
		PairingOutcome::Cancelled => Err("The client cancelled pairing. Start pairing again in the client.".into()),
		PairingOutcome::Rejected => Err("The request was rejected by a host operator.".into()),
		PairingOutcome::Cleared => {
			Err("Pairing was cleared by revocation or server shutdown. Start pairing again.".into())
		},
	}
}

